// Emits LaTeX fragments for the paper's evaluation section by running the
// reference JS implementation against the conformance corpus. The paper's
// numbers are therefore derived, not transcribed: if the corpus or the
// implementation changes, `make` regenerates them.
//
// Outputs (paper/generated/):
//   conformance-summary.tex  — macros: totals, pass counts, corpus coverage
//   conformance-vectors.tex  — longtable of every text vector and its result

const fs = require('fs');
const path = require('path');
const { normalizeText, sha256 } = require('../../public/normalize.js');

const FIXTURES_DIR = path.join(__dirname, '..', '..', 'normalization-hashes');
const OUT_DIR = path.join(__dirname, '..', 'generated');

function parseFrontmatter(content) {
    const m = content.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
    if (!m) return { metadata: null, body: content };
    const frontmatter = m[1];
    const body = m[2];
    const metadata = {};
    const desc = frontmatter.match(/^description:\s*(.+)$/m);
    if (desc) metadata.description = desc[1].trim();
    const charNorm = frontmatter.match(/^charNormalization:\s*"(.+)"$/m);
    if (charNorm) metadata.charNormalization = charNorm[1];
    const ocrRules = frontmatter.match(/ocrNormalizationRules:\n((?:\s+-[^\n]+\n?)+)/);
    if (ocrRules) {
        const pattern = ocrRules[1].match(/pattern:\s*"(.+)"/);
        const replacement = ocrRules[1].match(/replacement:\s*"(.*)"/);
        if (pattern && replacement) {
            metadata.ocrNormalizationRules = [{ pattern: pattern[1], replacement: replacement[1] }];
        }
    }
    return { metadata: Object.keys(metadata).length ? metadata : null, body };
}

function texEscape(s) {
    return s
        .replace(/\\/g, '\\textbackslash{}')
        .replace(/([#$%&_{}])/g, '\\$1')
        .replace(/~/g, '\\textasciitilde{}')
        .replace(/\^/g, '\\textasciicircum{}')
        .replace(/→/g, '$\\rightarrow$')
        .replace(/×/g, '$\\times$');
}

const files = fs.readdirSync(FIXTURES_DIR)
    .filter(f => f.endsWith('.md') && f !== 'README.md' && !f.startsWith('PLACEHOLDER'));

const vectors = files.map(filename => {
    const content = fs.readFileSync(path.join(FIXTURES_DIR, filename), 'utf8');
    const { metadata, body } = parseFrontmatter(content);
    const isImage = !!body.trim().match(/^!\[\]\((.+)\)$/);
    return {
        expectedHash: filename.replace('.md', ''),
        body: body.trimEnd(),
        metadata,
        description: metadata?.description || filename,
        isImage,
    };
});

const textVectors = vectors.filter(v => !v.isImage);
const imageVectors = vectors.filter(v => v.isImage);

let passes = 0;
const rows = textVectors.map(v => {
    const computed = sha256(normalizeText(v.body, v.metadata));
    const pass = computed === v.expectedHash;
    if (pass) passes += 1;
    return { ...v, pass };
});

if (passes !== textVectors.length) {
    // Fail loudly: the paper must not be built over a failing corpus.
    const failing = rows.filter(r => !r.pass).map(r => r.expectedHash.slice(0, 12));
    throw new Error(`Conformance FAILED for ${failing.length} vector(s): ${failing.join(', ')}`);
}

fs.mkdirSync(OUT_DIR, { recursive: true });

const summary = `% GENERATED by paper/scripts/gen-conformance-table.js — do not hand-edit.
\\newcommand{\\VectorTotal}{${vectors.length}}
\\newcommand{\\TextVectorCount}{${textVectors.length}}
\\newcommand{\\ImageVectorCount}{${imageVectors.length}}
\\newcommand{\\TextVectorPasses}{${passes}}
\\newcommand{\\CharNormVectorCount}{${textVectors.filter(v => v.metadata?.charNormalization).length}}
\\newcommand{\\OcrRuleVectorCount}{${textVectors.filter(v => v.metadata?.ocrNormalizationRules).length}}
`;
fs.writeFileSync(path.join(OUT_DIR, 'conformance-summary.tex'), summary);

const tableRows = rows
    .map(r => `${texEscape(r.description)} & \\texttt{${r.expectedHash.slice(0, 12)}} & ${r.pass ? '\\checkmark' : '\\textbf{FAIL}'} \\\\`)
    .join('\n');
const table = `% GENERATED by paper/scripts/gen-conformance-table.js — do not hand-edit.
\\begin{longtable}{p{8.2cm} l c}
\\toprule
\\textbf{Vector (description)} & \\textbf{Pinned hash (prefix)} & \\textbf{JS} \\\\
\\midrule
\\endhead
\\bottomrule
\\endfoot
${tableRows}
\\end{longtable}
`;
fs.writeFileSync(path.join(OUT_DIR, 'conformance-vectors.tex'), table);

console.log(`conformance: ${passes}/${textVectors.length} text vectors pass ` +
    `(${imageVectors.length} image vectors are exercised by the Android/iOS instrumented suites); ` +
    `fragments written to paper/generated/`);
